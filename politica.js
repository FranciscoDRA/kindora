// Reveal on scroll
const sections = document.querySelectorAll('.policy-section');
const observer = new IntersectionObserver((entries) => {
  entries.forEach(e => {
    if (e.isIntersecting) {
      e.target.classList.add('visible');
      observer.unobserve(e.target);
    }
  });
}, { threshold: 0.08 });
sections.forEach(s => observer.observe(s));
